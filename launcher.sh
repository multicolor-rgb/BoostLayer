#!/bin/sh
# Boostlayer launch shim.
#
# The Python frontend writes a 0600 runtime file (shell-quoted values) and calls:
#   launcher.sh /path/to/runtime.sh
#
# The shim deliberately uses only POSIX sh features and quotes every path.  The
# command vector is assembled with `set --`, so spaces and Windows-style paths
# in the .exe or its arguments remain intact.
set -u
umask 077

if [ "$#" -lt 1 ] || [ -z "${1:-}" ]; then
    printf '%s\n' "usage: launcher.sh RUNTIME_FILE" >&2
    exit 64
fi

BL_RUNTIME_FILE=$1
shift

if [ ! -r "$BL_RUNTIME_FILE" ]; then
    printf 'Boostlayer: runtime file not readable: %s\n' "$BL_RUNTIME_FILE" >&2
    exit 66
fi

# The runtime file is generated by Boostlayer with shlex.quote().  It exports the
# environment and ends with: set -- 'game.exe' 'argument' ...
# shellcheck disable=SC1090
. "$BL_RUNTIME_FILE"

BL_DEBUG=${BL_DEBUG:-0}
BL_GAMEMODE=${BL_GAMEMODE:-0}
BL_MANGOHUD=${BL_MANGOHUD:-0}
BL_GAMESCOPE=${BL_GAMESCOPE:-0}
BL_SCALING=${BL_SCALING:-native}
BL_FPS=${BL_FPS:-0}
BL_RUNNER=${BL_RUNNER:-}
BL_RUNNER_KIND=${BL_RUNNER_KIND:-wine}
BL_PROTON=${BL_PROTON:-}
BL_DIRECT=${BL_DIRECT:-0}
BL_PREFIX=${BL_PREFIX:-${WINEPREFIX:-}}
BL_LOG=${BL_LOG:-${HOME:-/tmp}/.config/boostlayer/last_run.log}
BL_CRT_SHADER=${BL_CRT_SHADER:-}
BL_WORKDIR=${BL_WORKDIR:-}
BL_MANGOHUD_CONFIG=${BL_MANGOHUD_CONFIG:-}
BL_MANGOHUD_LIB=${BL_MANGOHUD_LIB:-}
BL_MANGOHUD_BITS=${BL_MANGOHUD_BITS:-}

if [ "$#" -eq 0 ]; then
    printf '%s\n' "Boostlayer: runtime file did not define a game command." >&2
    exit 65
fi

# Environment and argv are now loaded; the 0600 runtime file is not needed.
rm -f "$BL_RUNTIME_FILE" 2>/dev/null || true

if [ "$BL_DEBUG" = "1" ]; then
    mkdir -p "$(dirname "$BL_LOG")" 2>/dev/null || true
    # Truncate on each run so the UI always shows the current invocation.
    : > "$BL_LOG" 2>/dev/null || true
    exec >>"$BL_LOG" 2>&1
    printf '%s\n' "=== Boostlayer launch $(date '+%Y-%m-%d %H:%M:%S') ==="
    printf 'Scaling: %s | FPS: %s | Ghost log: enabled\n' "$BL_SCALING" "$BL_FPS"
    printf 'Prefix: %s\n' "$BL_PREFIX"
    printf 'Runner: %s\n' "$BL_RUNNER"
else
    exec >/dev/null 2>&1
fi

if [ -n "$BL_WORKDIR" ] && [ -d "$BL_WORKDIR" ]; then
    cd "$BL_WORKDIR" || true
fi

if [ "$BL_DIRECT" = "1" ]; then
    # Steam already supplied the full Proton/Wine command line.  Do not wrap
    # it in another Wine invocation and do not touch Steam's own prefix.
    printf '%s\n' "Mode: Steam direct wrapper (Steam/Proton owns the prefix)."
else
    if [ -n "$BL_PREFIX" ]; then
        mkdir -p "$BL_PREFIX" 2>/dev/null || true
    fi

    if [ "$BL_RUNNER_KIND" = "proton" ] && [ -n "$BL_PROTON" ] && [ -x "$BL_PROTON" ]; then
        # Proton's script derives WINEPREFIX from STEAM_COMPAT_DATA_PATH.  Do
        # not inherit/export WINEPREFIX here; it can make Proton use the wrong
        # prefix.
        unset WINEPREFIX
        export STEAM_COMPAT_DATA_PATH="$BL_PREFIX"
        if [ -d "${HOME:-/nonexistent}/.steam/steam" ]; then
            export STEAM_COMPAT_CLIENT_INSTALL_PATH="${STEAM_COMPAT_CLIENT_INSTALL_PATH:-${HOME}/.steam/steam}"
        elif [ -d "${HOME:-/nonexistent}/.local/share/Steam" ]; then
            export STEAM_COMPAT_CLIENT_INSTALL_PATH="${STEAM_COMPAT_CLIENT_INSTALL_PATH:-${HOME}/.local/share/Steam}"
        fi
        printf 'Proton: %s\n' "$BL_PROTON"
        set -- "$BL_PROTON" run "$@"
    else
        export WINEPREFIX="$BL_PREFIX"
        # Resolve the Wine executable.  Runner archives normally expose files/bin/wine.
        if [ -z "$BL_RUNNER" ] || [ ! -x "$BL_RUNNER" ]; then
            if command -v wine >/dev/null 2>&1; then
                BL_RUNNER=$(command -v wine)
                printf 'Runner fallback: %s\n' "$BL_RUNNER"
            else
                printf '%s\n' "Boostlayer: no executable Wine runner found." >&2
                printf '%s\n' "Boostlayer: install Wine or download a runner in Runner Manager." >&2
                exit 127
            fi
        fi
        # Start with [WINE] [GAME.EXE] [LAUNCH ARGS].
        set -- "$BL_RUNNER" "$@"
    fi
fi

# [GAMESCOPE + UPSCALER / SHADER]
# -w/-h = resolution seen by the game, -W/-H = output resolution.
if [ "$BL_GAMESCOPE" = "1" ] && command -v gamescope >/dev/null 2>&1; then
    GS_USE=0
    GS_W=0
    GS_H=0
    GS_OUT_W=0
    GS_OUT_H=0
    GS_UPSCALER=""
    GS_SHARPNESS=""
    GS_INTEGER=0
    GS_STRETCH=0
    GS_SHADER=""

    case "$BL_SCALING" in
        fsr_720_1080)
            GS_USE=1; GS_W=1280; GS_H=720; GS_OUT_W=1920; GS_OUT_H=1080
            GS_UPSCALER=fsr; GS_SHARPNESS=8
            ;;
        fsr_1080_1440)
            GS_USE=1; GS_W=1920; GS_H=1080; GS_OUT_W=2560; GS_OUT_H=1440
            GS_UPSCALER=fsr; GS_SHARPNESS=8
            ;;
        fsr_1440_4k)
            GS_USE=1; GS_W=2560; GS_H=1440; GS_OUT_W=3840; GS_OUT_H=2160
            GS_UPSCALER=fsr; GS_SHARPNESS=8
            ;;
        nis_1080_1440)
            GS_USE=1; GS_W=1920; GS_H=1080; GS_OUT_W=2560; GS_OUT_H=1440
            GS_UPSCALER=nis; GS_SHARPNESS=8
            ;;
        integer)
            GS_USE=1; GS_W=1280; GS_H=720; GS_OUT_W=3840; GS_OUT_H=2160
            GS_INTEGER=1
            ;;
        crt)
            GS_USE=1; GS_W=1280; GS_H=720; GS_OUT_W=1920; GS_OUT_H=1080
            GS_STRETCH=1
            if [ -n "$BL_CRT_SHADER" ] && [ -r "$BL_CRT_SHADER" ]; then
                GS_SHADER=$BL_CRT_SHADER
            else
                printf 'CRT shader missing: %s\n' "$BL_CRT_SHADER"
            fi
            ;;
        *)
            # Native, Proton FSR and unknown values do not need the compositor.
            ;;
    esac

    if [ "$GS_USE" = "1" ]; then
        # Prepend the separator and wrappers with POSIX positional parameters.
        # This avoids eval and keeps quoted paths intact.
        set -- -- "$@"

        if [ -n "$GS_SHADER" ]; then
            set -- --reshade-effect "$GS_SHADER" "$@"
        fi
        if [ "$GS_INTEGER" = "1" ]; then
            set -- -S integer "$@"
        fi
        if [ "$GS_STRETCH" = "1" ]; then
            set -- -S stretch "$@"
        fi
        if [ -n "$GS_UPSCALER" ]; then
            set -- -F "$GS_UPSCALER" "$@"
        fi
        if [ -n "$GS_SHARPNESS" ]; then
            set -- --fsr-sharpness "$GS_SHARPNESS" \
                --nis-sharpness "$GS_SHARPNESS" "$@"
        fi
        case "$BL_FPS" in
            ''|*[!0-9]*) ;;
            *)
                if [ "$BL_FPS" -gt 0 ]; then
                    set -- -r "$BL_FPS" "$@"
                fi
                ;;
        esac
        set -- gamescope \
            -w "$GS_W" -h "$GS_H" \
            -W "$GS_OUT_W" -H "$GS_OUT_H" \
            -f --force-windows-fullscreen "$@"
    fi
fi

# [MANGOHUD]
# Prefer an explicit architecture-specific library.  This avoids the literal
# `$LIB` token in Debian's mangohud wrapper, which is not expanded reliably
# inside Proton/Steam Linux Runtime.
if [ "$BL_MANGOHUD" = "1" ]; then
    export MANGOHUD=1
    export MANGOHUD_CONFIG="$BL_MANGOHUD_CONFIG"
    if [ -n "$BL_MANGOHUD_LIB" ] && [ -r "$BL_MANGOHUD_LIB" ]; then
        export LD_PRELOAD="$BL_MANGOHUD_LIB${LD_PRELOAD:+:$LD_PRELOAD}"
        printf 'MangoHud: %s-bit %s\n' "${BL_MANGOHUD_BITS:-?}" "$BL_MANGOHUD_LIB"
    elif command -v mangohud >/dev/null 2>&1; then
        printf 'MangoHud: explicit library unavailable, using wrapper.\n'
        set -- mangohud "$@"
    else
        printf '%s\n' "MangoHud requested but the mangohud executable is not installed."
    fi
fi

# [GAMEMODERUN] must be the outermost wrapper in the chain.
if [ "$BL_GAMEMODE" = "1" ] && command -v gamemoderun >/dev/null 2>&1; then
    set -- gamemoderun "$@"
elif [ "$BL_GAMEMODE" = "1" ]; then
    printf '%s\n' "GameMode requested but gamemoderun is not installed."
fi

printf '%s\n' "Executing:"
INDEX=1
for ARG in "$@"; do
    printf '  [%s] %s\n' "$INDEX" "$ARG"
    INDEX=$((INDEX + 1))
done

exec "$@"
